-- table_id es nullable: solo los pedidos de canal MESA tienen mesa
-- física de salón. BARRA, TAKEAWAY y DELIVERY nunca tienen table_id
-- ni table_session_id — la barra en particular no gestiona espacio,
-- por lo que no existe (ni debe existir) ningún mecanismo de
-- exclusividad para ella, a diferencia de las mesas.
CREATE TABLE "orders" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "branch_id" integer NOT NULL,
  "table_id" integer,
  "employee_id" integer NOT NULL,
  "customer_id" integer,
  "table_session_id" integer,
  "channel" varchar(20) NOT NULL,
  "order_time" timestamp NOT NULL,
  "total_amount" decimal(10,2) NOT NULL,
  "status" varchar(50) NOT NULL,
  CHECK ("channel" IN ('MESA', 'BARRA', 'TAKEAWAY', 'DELIVERY')),
  CHECK (
    ("channel" = 'MESA' AND "table_id" IS NOT NULL)
    OR ("channel" <> 'MESA' AND "table_id" IS NULL AND "table_session_id" IS NULL)
  )
);

