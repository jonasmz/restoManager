-- Restaurant management schema - v3
-- Changes implemented (v1):
-- 1. orders.customer_id is nullable for anonymous consumers.
-- 2. inventory_movements provides stock ingress/egress traceability.
-- 3. ingredients is a catalog; stock is held per branch in branch_inventory.
-- 4. tables.operational_status only represents physical/operational availability.
-- 5. table_sessions represents actual table occupancy; application derives AVAILABLE/RESERVED/OCCUPIED.
-- 6. orders.table_session_id optionally links an order to its table occupancy session.
-- Changes implemented (v2 — audit fixes):
-- 7. deliveries.actual_time is nullable (unknown until the delivery actually completes).
-- 8. orders.table_id is nullable (delivery, takeaway, and bar orders have no dine-in table).
-- 9. Added UNIQUE constraints: tables(branch_id, number), gift_cards.card_number,
--    recipe_items(menu_item_id, ingredient_id), station_menu_items(station_id, menu_item_id),
--    menu_item_taxes(menu_item_id, tax_rate_id), order_discounts(order_id, discount_id).
-- 10. reviews.rating is constrained to 1-5; order_items.notes and reviews.comment are now optional.
-- 11. All PKs use GENERATED BY DEFAULT AS IDENTITY (was plain integer).
-- Changes implemented (v3 — bar consumption, corrected design):
-- 12. Bar consumption is NOT modeled as a table. It does not fit the exclusive-occupancy
--     semantics of tables/table_sessions: unrelated customers can consume at the bar
--     concurrently, and the system deliberately does not manage bar capacity/space.
--     orders.channel (MESA | BARRA | TAKEAWAY | DELIVERY) is the explicit, stored
--     classification. A CHECK constraint enforces that MESA requires table_id, and every
--     other channel has neither table_id nor table_session_id. Because the bar is not a row
--     in "tables", it is structurally unreservable — reservations.table_id can only ever
--     reference a dine-in table.
-- Dialect note: the partial unique index at the end uses PostgreSQL syntax.

