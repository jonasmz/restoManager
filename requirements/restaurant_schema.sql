-- Occupancy is represented by open/closed table sessions.
-- AVAILABLE / RESERVED / OCCUPIED are application-derived states and are not stored in tables.operational_status.
CREATE TABLE "table_sessions" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "table_id" integer NOT NULL,
  "guest_count" integer NOT NULL,
  "opened_at" timestamp NOT NULL,
  "closed_at" timestamp,
  CHECK ("guest_count" > 0),
  CHECK ("closed_at" IS NULL OR "closed_at" >= "opened_at")
);

-- Current stock balance per branch and ingredient.
CREATE TABLE "branch_inventory" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "branch_id" integer NOT NULL,
  "ingredient_id" integer NOT NULL,
  "stock_quantity" decimal(10,2) NOT NULL DEFAULT 0,
  UNIQUE ("branch_id", "ingredient_id"),
  CHECK ("stock_quantity" >= 0)
);

-- Inventory ledger. Quantity uses a signed convention:
-- PURCHASE > 0, SALE < 0, WASTE < 0, ADJUSTMENT may be positive or negative.
CREATE TABLE "inventory_movements" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "branch_id" integer NOT NULL,
  "ingredient_id" integer NOT NULL,
  "movement_type" varchar(50) NOT NULL,
  "quantity" decimal(10,2) NOT NULL,
  "movement_time" timestamp NOT NULL,
  "reference_type" varchar(50),
  "reference_id" integer,
  "employee_id" integer,
  CHECK ("movement_type" IN ('PURCHASE', 'SALE', 'WASTE', 'ADJUSTMENT')),
  CHECK ("quantity" <> 0)
);

