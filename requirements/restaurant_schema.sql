-- Restaurant management schema (resto_business) - v4, regenerado desde el esquema real
-- Este archivo es un documento de referencia/diseño; el esquema real y su historia
-- viven en las migraciones de EF Core (backend/business/.../Infrastructure/Persistence/Migrations).
-- v1-v3 se mantenían a mano y quedaron desactualizados a medida que las migraciones avanzaban
-- (Fases 4-11: baja lógica, disponibilidad por sucursal, punto de reposición, carta pública, etc.)
-- sin que nadie las volcara acá. v4 se generó a partir del esquema vivo de una base ya migrada
-- (información de information_schema/pg_catalog), no a mano, para que vuelva a ser fiel.
-- Para regenerarlo: `dotnet ef migrations script` (o inspeccionar la base migrada) y adaptar
-- al estilo de este archivo.
--
-- Changes implemented (v1):
-- 1. orders.customer_id is nullable for anonymous consumers.
-- 2. inventory_movements provides stock ingress/egress traceability.
-- 3. ingredients is a catalog; stock is held per branch in branch_inventory.
-- 4. tables.operational_status only represents physical/operational availability.
-- 5. table_sessions represents actual table occupancy; application derives AVAILABLE/RESERVED/OCCUPIED.
-- 6. orders.table_session_id optionally links an order to its table occupancy session.
-- Changes implemented (v2 — audit fixes):
-- 7. deliveries.actual_time is nullable (unknown until the delivery actually completes).
-- 8. orders.table_id is nullable (delivery, takeaway, and bar orders have no dine-in table).
-- 9. Added UNIQUE constraints: tables(branch_id, number), gift_cards.card_number,
--    recipe_items(menu_item_id, ingredient_id), station_menu_items(station_id, menu_item_id),
--    menu_item_taxes(menu_item_id, tax_rate_id), order_discounts(order_id, discount_id).
-- 10. reviews.rating is constrained to 1-5; order_items.notes and reviews.comment are now optional.
-- 11. All PKs use GENERATED BY DEFAULT AS IDENTITY (was plain integer).
-- Changes implemented (v3 — bar consumption, corrected design):
-- 12. Bar consumption is NOT modeled as a table. It does not fit the exclusive-occupancy
--     semantics of tables/table_sessions: unrelated customers can consume at the bar
--     concurrently, and the system deliberately does not manage bar capacity/space.
--     orders.channel (MESA | BARRA | TAKEAWAY | DELIVERY) is the explicit, stored
--     classification. A CHECK constraint enforces that MESA requires table_id, and every
--     other channel has neither table_id nor table_session_id. Because the bar is not a row
--     in "tables", it is structurally unreservable — reservations.table_id can only ever
--     reference a dine-in table.
-- Changes implemented (v4 — catch-up with Fases 4-12b, sin cambios de diseño nuevos acá):
-- 13. menu_items / ingredients: baja lógica (deleted_at nullable; el repositorio filtra las
--     filas borradas, no hay borrado físico ni cascada de recetas/inventario). Issue #47.
-- 14. menu_items.image_key (nullable): referencia a la imagen del plato en el storage de
--     archivos (servida bajo /media/menu), no la imagen en sí.
-- 15. ingredients.reorder_point: umbral de reposición usado por el reporte de bajo stock.
-- 16. menu_item_branch_availability (nueva tabla): disponibilidad del plato por sucursal,
--     UNIQUE (branch_id, menu_item_id) — reemplaza el booleano global que tenía menu_items.
-- 17. branches.public_slug (nullable, UNIQUE): slug de la carta pública por QR (Fase 11).
-- 18. employees.user_id (nullable, no es FK real: vive en otra base, resto_identity, servida
--     por la Auth API): rastro de qué empleado ya tiene un login vinculado; lo setea el panel
--     de administración al dar de alta el acceso, nunca a mano.
-- Dialect note: the partial unique index at the end uses PostgreSQL syntax.

CREATE TABLE "branch_inventory" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "branch_id" integer NOT NULL,
  "ingredient_id" integer NOT NULL,
  "stock_quantity" decimal(10,2) NOT NULL,
  UNIQUE ("branch_id", "ingredient_id"),
  CHECK ("stock_quantity" >= 0)
);

CREATE TABLE "branches" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "restaurant_id" integer NOT NULL,
  "name" varchar(100) NOT NULL,
  "address" varchar(255) NOT NULL,
  "phone" varchar(20) NOT NULL,
  "email" varchar(100) NOT NULL,
  "opening_time" time NOT NULL,
  "closing_time" time NOT NULL,
  "public_slug" varchar(60),
  UNIQUE ("public_slug")
);

CREATE TABLE "categories" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(100) NOT NULL,
  "description" varchar(255) NOT NULL
);

CREATE TABLE "customers" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "first_name" varchar(100) NOT NULL,
  "last_name" varchar(100) NOT NULL,
  "email" varchar(100) NOT NULL,
  "phone" varchar(20) NOT NULL,
  "loyalty_points" integer NOT NULL
);

CREATE TABLE "deliveries" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "order_id" integer NOT NULL,
  "driver_id" integer NOT NULL,
  "delivery_address" varchar(255) NOT NULL,
  "estimated_time" timestamp NOT NULL,
  "actual_time" timestamp,
  "status" varchar(50) NOT NULL
);

CREATE TABLE "delivery_drivers" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "employee_id" integer NOT NULL,
  "vehicle_type" varchar(50) NOT NULL,
  "license_plate" varchar(20) NOT NULL
