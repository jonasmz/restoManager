CREATE TABLE "menu_items" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "category_id" integer NOT NULL,
  "name" varchar(100) NOT NULL,
  "description" varchar(255) NOT NULL,
  "price" decimal(10,2) NOT NULL,
